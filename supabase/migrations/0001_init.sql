-- Stock may only change through the RPCs below (they set app.allow_stock).
create or replace function public.guard_stock_change()
returns trigger language plpgsql as $$
begin
  if new.stock_qty is distinct from old.stock_qty
     and coalesce(current_setting('app.allow_stock', true), '') <> '1' then
    raise exception 'stock_qty can only be changed through create_sale / void_sale / adjust_stock';
  end if;
  new.updated_at := now();
  return new;
end $$;
drop trigger if exists items_guard_stock on public.items;
create trigger items_guard_stock before update on public.items
  for each row execute function public.guard_stock_change();

