-- China container sales & stock tracker — initial schema
-- Run in the Supabase SQL editor (or `supabase db push`). Idempotent where practical.

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- Profiles (one per auth user) and devices
-- ---------------------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  login_slug text unique,                    -- "hasan" → signs in as hasan@family.local
  display_name text not null,
  display_name_ar text,
  role text not null default 'seller' check (role in ('owner', 'seller')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- The app has no server, so new users are created from the browser with
-- supabase.auth.signUp. Only names the owner has invited first are accepted.
create table if not exists public.invites (
  login_slug text primary key,
  display_name text not null,
  display_name_ar text,
  role text not null default 'seller' check (role in ('owner', 'seller')),
  created_by uuid references public.profiles (id),
  created_at timestamptz not null default now()
);

create table if not exists public.devices (
  id uuid primary key,                       -- generated by the browser, kept in localStorage
  user_id uuid not null references public.profiles (id) on delete cascade,
  nickname text not null,                    -- "Mohamad's iPhone"
  user_agent text,
  device_label text,                         -- parsed: "iPhone · Safari 26"
  first_seen timestamptz not null default now(),
  last_seen timestamptz not null default now()
);
create index if not exists devices_user_idx on public.devices (user_id);

-- Create a profile row whenever an auth user is created (owner creates users
-- through the admin API with display_name/role in user metadata).
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_slug text := lower(split_part(new.email, '@', 1));
  v_inv public.invites%rowtype;
begin
  if (select count(*) from public.profiles) = 0 then
    -- very first account becomes the owner (bootstrap, done once during setup)
    insert into public.profiles (id, login_slug, display_name, display_name_ar, role)
    values (new.id, v_slug,
            coalesce(new.raw_user_meta_data ->> 'display_name', initcap(v_slug)),
            new.raw_user_meta_data ->> 'display_name_ar', 'owner');
    return new;
  end if;

  select * into v_inv from public.invites where login_slug = v_slug;
  if not found then
    raise exception 'NOT_INVITED: ask the owner to add you first';
  end if;
  insert into public.profiles (id, login_slug, display_name, display_name_ar, role)
  values (new.id, v_slug, v_inv.display_name, v_inv.display_name_ar, v_inv.role);
  delete from public.invites where login_slug = v_slug;
  return new;
end $$;

-- Names shown on the login screen (before sign-in), so callable anonymously.
create or replace function public.list_login_names()
returns table (id uuid, login_slug text, display_name text, display_name_ar text, role text)
language sql stable security definer set search_path = public as $$
  select id, login_slug, display_name, display_name_ar, role
  from public.profiles where active order by created_at;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users for each row execute function public.handle_new_user();

create or replace function public.is_owner()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'owner' and p.active);
$$;

create or replace function public.is_active_user()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles p where p.id = auth.uid() and p.active);
$$;

