-- keep payment_status consistent with paid_usd / total_usd
create or replace function public.sales_payment_status()
returns trigger language plpgsql as $$
begin
  new.payment_status := case
    when new.paid_usd <= 0 then 'unpaid'
    when new.paid_usd >= new.total_usd then 'paid'
    else 'partial' end;
  return new;
end $$;
drop trigger if exists sales_payment_status_trg on public.sales;
create trigger sales_payment_status_trg before insert or update of paid_usd, total_usd on public.sales
  for each row execute function public.sales_payment_status();

-- ---------------------------------------------------------------------------
-- RPCs (security definer: all writes to stock/sales go through these)
-- ---------------------------------------------------------------------------
create or replace function public.register_device(
  p_device_id uuid, p_nickname text, p_user_agent text, p_device_label text
) returns void language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null or not public.is_active_user() then
    raise exception 'not signed in';
  end if;
  insert into public.devices (id, user_id, nickname, user_agent, device_label)
  values (p_device_id, auth.uid(), coalesce(nullif(trim(p_nickname), ''), p_device_label, 'Phone'), p_user_agent, p_device_label)
  on conflict (id) do update
    set user_id = excluded.user_id,
        nickname = case when excluded.nickname is not null and excluded.nickname <> '' then excluded.nickname else devices.nickname end,
        user_agent = excluded.user_agent,
        device_label = excluded.device_label,
        last_seen = now();
end $$;

-- p_lines: [{"item_id": uuid, "qty": int, "unit_price_usd": numeric}, ...]
create or replace function public.create_sale(
  p_device_id uuid,
  p_customer_name text,
  p_location text,
  p_note text,
  p_paid_usd numeric,
  p_sold_at timestamptz,
  p_lines jsonb
) returns uuid language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_sale_id uuid;
  v_customer_id uuid;
  v_total numeric(12, 2) := 0;
  v_line jsonb;
  v_item public.items%rowtype;
  v_qty int;
  v_price numeric(10, 2);
begin
  if v_uid is null or not public.is_active_user() then
    raise exception 'not signed in';
  end if;
  if p_lines is null or jsonb_array_length(p_lines) = 0 then
    raise exception 'sale has no lines';
  end if;
  if p_device_id is not null and not exists (select 1 from public.devices where id = p_device_id) then
    p_device_id := null;
  end if;

  if nullif(trim(p_customer_name), '') is not null then
    insert into public.customers (name, location, created_by)
    values (trim(p_customer_name), nullif(trim(p_location), ''), v_uid)
    on conflict (lower(name)) do update
      set location = coalesce(nullif(trim(excluded.location), ''), customers.location)
    returning id into v_customer_id;
  end if;

  perform set_config('app.allow_stock', '1', true);

  insert into public.sales (seller_id, device_id, customer_id, customer_name, location, sold_at, note, paid_usd)
  values (v_uid, p_device_id, v_customer_id, nullif(trim(p_customer_name), ''), nullif(trim(p_location), ''),
          coalesce(p_sold_at, now()), nullif(trim(p_note), ''), coalesce(p_paid_usd, 0))
  returning id into v_sale_id;

  for v_line in select * from jsonb_array_elements(p_lines) loop
    v_qty := (v_line ->> 'qty')::int;
    v_price := (v_line ->> 'unit_price_usd')::numeric;
    if v_qty is null or v_qty <= 0 then
      raise exception 'invalid quantity';
    end if;
    select * into v_item from public.items where id = (v_line ->> 'item_id')::uuid for update;
    if not found or not v_item.active then
      raise exception 'item not found';
    end if;
    if v_item.stock_qty < v_qty then
      raise exception 'INSUFFICIENT_STOCK:%:%', v_item.sheet_ref, v_item.stock_qty;
    end if;
    insert into public.sale_lines (sale_id, item_id, qty, unit_price_usd, unit_cost_usd)
    values (v_sale_id, v_item.id, v_qty, coalesce(v_price, v_item.default_price_usd),
            coalesce(v_item.landed_cost_usd, v_item.cost_usd));
    update public.items set stock_qty = stock_qty - v_qty where id = v_item.id;
    insert into public.stock_movements (item_id, delta, reason, ref_sale_id, user_id, device_id)
    values (v_item.id, -v_qty, 'sale', v_sale_id, v_uid, p_device_id);
    v_total := v_total + v_qty * coalesce(v_price, v_item.default_price_usd);
  end loop;

  update public.sales set total_usd = v_total,
                          paid_usd = least(coalesce(p_paid_usd, 0), v_total)
   where id = v_sale_id;
  if coalesce(p_paid_usd, 0) > 0 then
    insert into public.payments (sale_id, amount_usd, recorded_by, device_id, note)
    values (v_sale_id, least(p_paid_usd, v_total), v_uid, p_device_id, 'at sale');
  end if;
  return v_sale_id;
end $$;

-- Owners can void any sale; a seller can void their own sale within 24 hours.
create or replace function public.void_sale(p_sale_id uuid, p_reason text, p_device_id uuid)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_sale public.sales%rowtype;
  v_line record;
begin
  if v_uid is null or not public.is_active_user() then
    raise exception 'not signed in';
  end if;
  select * into v_sale from public.sales where id = p_sale_id for update;
  if not found then raise exception 'sale not found'; end if;
  if v_sale.voided then raise exception 'already voided'; end if;
  if not public.is_owner() and not (v_sale.seller_id = v_uid and v_sale.created_at > now() - interval '24 hours') then
    raise exception 'not allowed';
  end if;
  if nullif(trim(p_reason), '') is null then raise exception 'reason required'; end if;

  perform set_config('app.allow_stock', '1', true);
  for v_line in select * from public.sale_lines where sale_id = p_sale_id loop
    update public.items set stock_qty = stock_qty + v_line.qty where id = v_line.item_id;
    insert into public.stock_movements (item_id, delta, reason, ref_sale_id, note, user_id, device_id)
    values (v_line.item_id, v_line.qty, 'void', p_sale_id, p_reason, v_uid, p_device_id);
  end loop;
  update public.sales set voided = true, void_reason = trim(p_reason), voided_by = v_uid, voided_at = now()
   where id = p_sale_id;
end $$;

create or replace function public.record_payment(p_sale_id uuid, p_amount numeric, p_device_id uuid, p_note text)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_sale public.sales%rowtype;
begin
  if v_uid is null or not public.is_active_user() then raise exception 'not signed in'; end if;
  if p_amount is null or p_amount = 0 then raise exception 'amount required'; end if;
  select * into v_sale from public.sales where id = p_sale_id for update;
  if not found or v_sale.voided then raise exception 'sale not found'; end if;
  insert into public.payments (sale_id, amount_usd, recorded_by, device_id, note)
  values (p_sale_id, p_amount, v_uid, p_device_id, nullif(trim(p_note), ''));
  update public.sales set paid_usd = greatest(0, paid_usd + p_amount) where id = p_sale_id;
end $$;

-- Owner-only manual stock change (returns, damaged goods, counting corrections).
create or replace function public.adjust_stock(p_item_id uuid, p_delta int, p_reason text, p_note text, p_device_id uuid)
returns void language plpgsql security definer set search_path = public as $$
declare v_uid uuid := auth.uid();
begin
  if not public.is_owner() then raise exception 'owner only'; end if;
  if p_delta = 0 then raise exception 'delta required'; end if;
  if p_reason not in ('adjustment', 'return', 'damaged') then raise exception 'bad reason'; end if;
  perform set_config('app.allow_stock', '1', true);
  update public.items set stock_qty = stock_qty + p_delta where id = p_item_id;
  insert into public.stock_movements (item_id, delta, reason, note, user_id, device_id)
  values (p_item_id, p_delta, p_reason, nullif(trim(p_note), ''), v_uid, p_device_id);
end $$;

-- Used by the import script (service role) to set opening stock.
create or replace function public.set_initial_stock(p_item_id uuid, p_qty int)
returns void language plpgsql security definer set search_path = public as $$
begin
  if auth.role() <> 'service_role' and not public.is_owner() then raise exception 'owner only'; end if;
  perform set_config('app.allow_stock', '1', true);
  update public.items set initial_qty = p_qty, stock_qty = p_qty where id = p_item_id;
  insert into public.stock_movements (item_id, delta, reason, note, user_id)
  values (p_item_id, p_qty, 'initial', 'opening stock from order sheet', auth.uid());
end $$;

-- ---------------------------------------------------------------------------
-- Reporting views (security_invoker so RLS applies to the caller)
-- ---------------------------------------------------------------------------
create or replace view public.v_item_stats with (security_invoker = true) as
select i.id as item_id, i.sheet_ref,
       coalesce(sum(l.qty) filter (where not s.voided), 0)::int as sold_qty,
       coalesce(sum(l.line_total) filter (where not s.voided), 0)::numeric(12,2) as revenue_usd,
       coalesce(sum(l.qty * (l.unit_price_usd - l.unit_cost_usd)) filter (where not s.voided), 0)::numeric(12,2) as profit_usd
from public.items i
left join public.sale_lines l on l.item_id = i.id
left join public.sales s on s.id = l.sale_id
group by i.id, i.sheet_ref;

create or replace view public.v_seller_stats with (security_invoker = true) as
select p.id as seller_id, p.display_name,
       count(distinct s.id) filter (where not s.voided)::int as sales_count,
       coalesce(sum(l.qty) filter (where not s.voided), 0)::int as units_sold,
       coalesce(sum(l.line_total) filter (where not s.voided), 0)::numeric(12,2) as revenue_usd,
       coalesce(sum(l.qty * (l.unit_price_usd - l.unit_cost_usd)) filter (where not s.voided), 0)::numeric(12,2) as profit_usd
from public.profiles p
left join public.sales s on s.seller_id = p.id
left join public.sale_lines l on l.sale_id = s.id
group by p.id, p.display_name;

create or replace view public.v_receivables with (security_invoker = true) as
select s.id as sale_id, s.sale_no, s.customer_id, s.customer_name, s.location, s.seller_id, s.sold_at,
       s.total_usd, s.paid_usd, (s.total_usd - s.paid_usd)::numeric(12,2) as due_usd
from public.sales s
where not s.voided and s.paid_usd < s.total_usd;

